    public void cargarDatos() {
        ArrayList<Donacion> donaciones = this.controlador.getDonaciones();
        String[] columnas = {"Numero", "Empresa", "Tipo", "Kilos"};
        Object[][] datos = new Object[donaciones.size()][4];

        for (int i = 0; i < donaciones.size(); i++) {
            Donacion donacion = donaciones.get(i);
            datos[i][0] = donacion.getNumero();
            datos[i][1] = donacion.getEmpresa().getNombre();
            datos[i][2] = donacion.getNombreTipo();
            datos[i][3] = donacion.getKilos();
        }

        this.tblDonaciones.setModel(new DefaultTableModel(datos, columnas));
    }

    @Override
    public void actualizar() {
        this.cargarDatos();
    }

