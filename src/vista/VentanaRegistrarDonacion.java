    public void cargarDatos() {
        this.empresas = this.controlador.getEmpresas();
        String[] lineas = new String[this.empresas.size()];
        for (int i = 0; i < this.empresas.size(); i++) {
            Empresa empresa = this.empresas.get(i);
            lineas[i] = empresa.getNombre() + " (" + empresa.getRut() + ")";
        }
        this.lstEmpresas.setListData(lineas);

        this.lblNumero.setText("Donacion numero: " + this.controlador.getProximoNumeroDonacion());
        this.txtKilos.setText("");
    }

    @Override
    public void actualizar() {
        this.cargarDatos();
    }

