    public void cargarDatos() {
        this.adopciones = this.controlador.getAdopciones();
        String[] lineas = new String[this.adopciones.size()];
        for (int i = 0; i < this.adopciones.size(); i++) {
            Adopcion adopcion = this.adopciones.get(i);
            lineas[i] = adopcion.getNumero() + " - " + adopcion.getAnimal().getNombre()
                    + " - Familia " + adopcion.getFamilia().getApellido();
        }
        this.lstAdopciones.setListData(lineas);
    }

    public void actualizar() {
        this.cargarDatos();
    }

