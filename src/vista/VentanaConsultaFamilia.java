    public void cargarDatos() {
        ArrayList<Familia> familias;
        if (this.rbApellido.isSelected()) {
            familias = this.controlador.getFamiliasOrdenadasPorApellido();
        } else {
            familias = this.controlador.getFamiliasOrdenadasPorAdopciones();
        }

        String[] lineas = new String[familias.size()];
        for (int i = 0; i < familias.size(); i++) {
            Familia familia = familias.get(i);
            lineas[i] = familia.getApellido() + " (" + familia.getCedula() + ") - Adopciones: "
                    + this.controlador.cantidadAdopcionesDeFamilia(familia);
        }
        this.lstFamilias.setListData(lineas);
    }

