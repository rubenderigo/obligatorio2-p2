    public void cargarDatos() {
        this.animalesDisponibles = this.controlador.getAnimalesDisponibles();
        String[] textosAnimales = new String[this.animalesDisponibles.size()];
        for (int i = 0; i < this.animalesDisponibles.size(); i++) {
            Animal animal = this.animalesDisponibles.get(i);
            textosAnimales[i] = animal.getCodigo() + " - " + animal.getNombre();
        }
        this.lstAnimales.setListData(textosAnimales);

        this.familias = this.controlador.getFamilias();
        String[] textosFamilias = new String[this.familias.size()];
        for (int i = 0; i < this.familias.size(); i++) {
            Familia familia = this.familias.get(i);
            textosFamilias[i] = familia.getApellido() + " (" + familia.getCedula() + ")";
        }
        this.lstFamilias.setListData(textosFamilias);

        this.lblNumero.setText("Adopcion numero: " + this.controlador.getProximoNumeroAdopcion());
        this.lblPeso.setText("Peso:");
        this.lblTemperamento.setText("Temperamento:");
        this.txtComentarios.setText("");
    }

