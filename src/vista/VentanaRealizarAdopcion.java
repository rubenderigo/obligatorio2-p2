    private void btnAdoptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdoptarActionPerformed
        Animal animal = null;
        int posicionAnimal = this.lstAnimales.getSelectedIndex();
        if (posicionAnimal >= 0) {
            animal = this.animalesDisponibles.get(posicionAnimal);
        }

        Familia familia = null;
        int posicionFamilia = this.lstFamilias.getSelectedIndex();
        if (posicionFamilia >= 0) {
            familia = this.familias.get(posicionFamilia);
        }

        try {
            int numero = this.controlador.getProximoNumeroAdopcion();
            this.controlador.realizarAdopcion(animal, familia, this.txtComentarios.getText().trim());
            JOptionPane.showMessageDialog(this, "Adopcion numero " + numero + " realizada");
            this.principal.actualizar();
            this.cargarDatos();
        } catch (DatoInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnAdoptarActionPerformed

    private void lstAnimalesValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstAnimalesValueChanged
        int posicion = this.lstAnimales.getSelectedIndex();
        if (posicion >= 0) {
            Animal animal = this.animalesDisponibles.get(posicion);
            this.lblPeso.setText("Peso: " + animal.getPeso() + " kg");
            this.lblTemperamento.setText("Temperamento: " + animal.getTemperamento());
        }
    }//GEN-LAST:event_lstAnimalesValueChanged

