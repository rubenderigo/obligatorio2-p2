    private void selectorArchivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_selectorArchivoActionPerformed
        if (evt.getActionCommand().equals(JFileChooser.APPROVE_SELECTION)) {
            String ruta = this.selectorArchivo.getSelectedFile().getAbsolutePath();
            int cantidadErrores = this.controlador.importarDonaciones(ruta);
            if (cantidadErrores == 0) {
                JOptionPane.showMessageDialog(this, "Importacion finalizada sin errores");
            } else {
                JOptionPane.showMessageDialog(this, "Importacion finalizada con " + cantidadErrores
                        + " lineas con error. Se genero el archivo de errores en la misma carpeta.");
            }
            this.dispose();
        } else {
            this.dispose();
        }
    }//GEN-LAST:event_selectorArchivoActionPerformed

