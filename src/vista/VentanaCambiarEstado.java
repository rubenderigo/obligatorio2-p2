    public void cargarDatos() {
        this.animales = this.controlador.getAnimalesNoEntregados();
        String[] lineas = new String[this.animales.size()];
        for (int i = 0; i < this.animales.size(); i++) {
            Animal animal = this.animales.get(i);
            String color;
            if (animal.getEstado().equals("Disponible para adoptar")) {
                color = "green";
            } else {
                color = "red";
            }
            lineas[i] = "<html><font color='" + color + "'>" + animal.getCodigo() + " - " + animal.getNombre()
                    + " - " + animal.getEstado() + "</font></html>";
        }
        this.lstAnimales.setListData(lineas);
    }

